# uint.sh — 引数・環境変数で受けた秒数などが「ASCII の数字だけでできた整数」かを確かめる
# shellcheck shell=sh  # shebang を持たない source 専用ファイル (bash / zsh / sh のどれからも読める形で書く)
#
# uint_ok <値> <最大の桁数>: rc 0 = 正しい / 1 = 空か数字以外を含む / 2 = 桁が多すぎる。
# エラー文と終了コードは呼ぶ側が決める (文言はテストが字面で見ている)。
#
# 🚨 [0-9] / [!0-9] でなく 0123456789 を列挙する: bash 3.2 (/bin/bash) の ja_JP.UTF-8 では [!0-9] が全角数字に一致せず、
#    「１２」を整数として通す (2026-10-15 に実測)。通った値は後段の [ -gt ] や runtimeout で別の失敗になる
# 🚨 桁の上限を必ず置く: 桁が多いと [ -gt ] / [ -ge ] は integer expected で偽を返し (19 桁から)、比べる側の上限が黙って外れる。
#    runtimeout は 9223372036 秒 (MaxInt64 / 1e9) を超える値を誤用 (rc=125) として拒む。9 桁までならどちらにも当たらない
uint_ok() {
  case "$1" in
    '' | *[!0123456789]*) return 1 ;;
  esac
  [ "${#1}" -le "$2" ] || return 2
}
