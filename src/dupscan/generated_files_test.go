package main

import (
	"encoding/json"
	"strings"
	"testing"
)

const generatedBaseGo = `package p

func Sum(xs []int, f func(int) bool) (int, int) {
	total, count := 0, 0
	for i, x := range xs {
		if f(x) && i%2 == 0 {
			total += x * 3
			count++
		} else if x > 10 {
			total -= x
		}
	}
	return total, count
}
`

// generatedCopyGo は generatedBaseGo と同じ本体の関数を、生成ファイルの見出しの下に置いたもの (Go の adapter は単位を出さない)。
var generatedCopyGo = "// Code generated by hand. DO NOT EDIT.\n\n" + strings.Replace(generatedBaseGo, "func Sum(", "func Sum2(", 1)

// 生成ファイルの見出しを付けた写しは単位として比べないが、gate はそのファイルを読まなかったことを 1 行目に出す (黙って「新しい重複なし」にしない)。
func TestGateCountsNewGeneratedFiles(t *testing.T) {
	root := repoWith(t, map[string]string{"p/a.go": generatedBaseGo})
	gitRun(t, root, "add", ".")
	gitRun(t, root, "commit", "-q", "-m", "base")
	writeFile(t, root, "p/gen.go", generatedCopyGo)
	gitRun(t, root, "add", ".")
	gitRun(t, root, "commit", "-q", "-m", "head")

	rc, out, errs := runGateCmd(t, "-base", "HEAD~1", root)
	if rc != 0 {
		t.Fatalf("rc=%d (生成ファイルは止めない) err=%q", rc, errs)
	}
	first, _, _ := strings.Cut(out, "\n")
	if !strings.Contains(first, "生成ファイルとして読まなかった新しい・書き換えたファイル 1") {
		t.Errorf("1 行目に読まなかった生成ファイルの数が無い: %q", first)
	}
	_, verbose, _ := runGateCmd(t, "-base", "HEAD~1", "-v", root)
	if !strings.Contains(verbose, "生成ファイルとして読まなかった: p/gen.go") {
		t.Errorf("-v に一覧が無い: %q", verbose)
	}
	_, js, _ := runGateCmd(t, "-base", "HEAD~1", "-format", "json", root)
	var s struct {
		New []string `json:"new_generated_files"`
	}
	if err := json.Unmarshal([]byte(js), &s); err != nil || len(s.New) != 1 || s.New[0] != "p/gen.go" {
		t.Errorf("new_generated_files = %v (err %v)", s.New, err)
	}

	_, xc, _ := runGateCmd(t, "-base", "HEAD~1", "-format", "xcode", root)
	if !strings.Contains(xc, "p/gen.go:1:1: warning:") || !strings.Contains(xc, "dupscan.gate.generated") {
		t.Errorf("xcode の形式に生成ファイルの warning が無い: %q", xc)
	}

	// base にも同じ中身であった生成ファイルは数えない (本物の生成コードがある repo で毎回出さない)
	rc, out, errs = runGateCmd(t, "-base", "HEAD", root)
	if rc != 0 || strings.Contains(out, "生成ファイル") {
		t.Errorf("base にもある生成ファイルを新しいと数えた: rc=%d out=%q err=%q", rc, out, errs)
	}

	// base で既に生成ファイルだったファイルに写しを足すと、中身が変わったので数える (見出しを付けた commit の後もずっと見える)
	writeFile(t, root, "p/gen.go", generatedCopyGo+strings.Replace(strings.TrimPrefix(generatedBaseGo, "package p\n"), "func Sum(", "func Sum4(", 1))
	rc, out, errs = runGateCmd(t, "-base", "HEAD", root)
	if first, _, _ := strings.Cut(out, "\n"); rc != 0 || !strings.Contains(first, "生成ファイルとして読まなかった新しい・書き換えたファイル 1") {
		t.Errorf("書き換えた生成ファイルを数えない: rc=%d out=%q err=%q", rc, out, errs)
	}
}

// 見出しの無いファイルへ移した写しは今までどおり止まる (上のテストの緑が、gate が Go を読んでいないことで出ていないかの対照)。
func TestGateStopsSameCopyWithoutGeneratedHeader(t *testing.T) {
	root := repoWith(t, map[string]string{"p/a.go": generatedBaseGo})
	gitRun(t, root, "add", ".")
	gitRun(t, root, "commit", "-q", "-m", "base")
	writeFile(t, root, "p/plain.go", strings.Replace(generatedBaseGo, "func Sum(", "func Sum3(", 1))
	if rc, out, errs := runGateCmd(t, "-base", "HEAD", root); rc != 1 {
		t.Errorf("rc=%d out=%q err=%q", rc, out, errs)
	}
}

func TestReportCountsGeneratedFiles(t *testing.T) {
	root := repoWith(t, map[string]string{"p/a.go": generatedBaseGo, "p/gen.go": generatedCopyGo})
	rc, out, errs := runReport(t, root)
	if rc != 0 || !strings.Contains(out, "生成ファイルとして読まなかったファイル 1") {
		t.Errorf("rc=%d out=%q err=%q", rc, out, errs)
	}
	_, js, _ := runReport(t, "-format", "json", root)
	var s struct {
		Generated []string `json:"generated_files"`
	}
	if err := json.Unmarshal([]byte(js), &s); err != nil || len(s.Generated) != 1 || s.Generated[0] != "p/gen.go" {
		t.Errorf("generated_files = %v (err %v)", s.Generated, err)
	}
}
