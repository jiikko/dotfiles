// 当たる語のない文は、家族ごとの走査を省く (語の表は同じ)。
var addStateAny = pyre.NewLazyFrom(func() string {
	parts := make([]string, len(addState))
	for i, row := range addState {
		parts[i] = "(?:" + row.pattern + ")"
	}
	return joinPattern(parts)
}, 0)

func joinPattern(parts []string) string {
	out := ""
	for i, p := range parts {
		if i > 0 {
			out += "|"
		}
		out += p
	}
	return out
}

