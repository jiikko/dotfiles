// CasemapFile は str.casefold・lower・swapcase の記録 (testdata/golden/ の中)。internal/pyunicode の大文字小文字の表のもとで、
// CasemapTablesPath の Go のソースにする。
const (
	CasemapFile       = "casemap.json"
	CasemapTablesPath = "internal/pyunicode/case_gen.go"
)

// CaseRow は [cp, [結果の cp ...]]。結果が元の 1 字と違う字だけを持つ。
type CaseRow struct {
	CP rune
	To []rune
}

// MarshalJSON は [cp, [cp ...]] の形にする。
func (c CaseRow) MarshalJSON() ([]byte, error) { return marshalTuple(c.CP, c.To) }

// UnmarshalJSON は [cp, [cp ...]] を読む。
func (c *CaseRow) UnmarshalJSON(b []byte) error { return unmarshalTuple(b, &c.CP, &c.To) }

// DecimalRow は [cp, 値]。unicodedata.decimal(chr(cp)) が返す 0〜9。
type DecimalRow struct {
	CP    rune
	Value int
}

// MarshalJSON は [cp, 値] の形にする。
func (d DecimalRow) MarshalJSON() ([]byte, error) { return marshalTuple(d.CP, d.Value) }

// UnmarshalJSON は [cp, 値] を読む。
func (d *DecimalRow) UnmarshalJSON(b []byte) error { return unmarshalTuple(b, &d.CP, &d.Value) }

// CaseString は文字列 (cp の列) 1 つに 3 つのメソッドを当てた記録。
type CaseString struct {
	S, Casefold, Lower, Swapcase []rune
}

// MarshalJSON は [元, casefold, lower, swapcase] の形にする。
func (c CaseString) MarshalJSON() ([]byte, error) {
	return marshalTuple(c.S, c.Casefold, c.Lower, c.Swapcase)
}

// UnmarshalJSON は [元, casefold, lower, swapcase] を読む。
func (c *CaseString) UnmarshalJSON(b []byte) error {
	return unmarshalTuple(b, &c.S, &c.Casefold, &c.Lower, &c.Swapcase)
}

// CasemapBody は py/record_casemap.py の出力。
type CasemapBody struct {
	Casefold []CaseRow `json:"casefold"`
	Lower    []CaseRow `json:"lower"`
	Swapcase []CaseRow `json:"swapcase"`
	// Cased と CaseIgnorable は語末の Σ の規則に使う字の範囲 (py/record_casemap.py の冒頭に求め方を書いた)。
	Cased         []CPRange         `json:"cased"`
	CaseIgnorable []CPRange         `json:"case_ignorable"`
	Decimal       []DecimalRow      `json:"decimal"`
	Digests       map[string]string `json:"digests"`
	Cases         []CaseString      `json:"cases"`
}

// CasemapGolden は casemap.json の中身。
type CasemapGolden struct {
	Header Header
	CasemapBody
}

// MarshalCasemap は CasemapGolden を決まったバイト列にする。
func MarshalCasemap(g CasemapGolden) ([]byte, error) {
	header, err := marshalField("header", g.Header)
	if err != nil {
		return nil, err
	}
	parts := []string{header}
	for _, f := range []struct {
		name string
		v    any
	}{{"casefold", g.Casefold}, {"lower", g.Lower}, {"swapcase", g.Swapcase}, {"cased", g.Cased}, {"case_ignorable", g.CaseIgnorable}, {"decimal", g.Decimal}, {"cases", g.Cases}} {
		lines, err := marshalLinesAny(f.v)
		if err != nil {
			return nil, err
		}
		parts = append(parts, fmt.Sprintf("%q: %s", f.name, lines))
	}
	digests, err := marshalField("digests", g.Digests)
	if err != nil {
		return nil, err
	}
	parts = append(parts, digests)
	return []byte("{\n" + strings.Join(parts, ",\n") + "\n}\n"), nil
}

// ParseCasemap は MarshalCasemap が書いたバイト列を CasemapGolden に読む。
func ParseCasemap(body []byte) (CasemapGolden, error) {
	var file struct {
		Header Header `json:"header"`
		CasemapBody
	}
	dec := json.NewDecoder(bytes.NewReader(body))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&file); err != nil {
		return CasemapGolden{}, fmt.Errorf("casemap の記録を読めません: %w", err)
	}
	return CasemapGolden{Header: file.Header, CasemapBody: file.CasemapBody}, nil
}

// RecordCasemap は本家の Python で大文字小文字の変換を全コードポイントについて読む。
func (r Runner) RecordCasemap(ctx context.Context, header Header) (CasemapGolden, error) {
	sb, err := newSandbox()
	if err != nil {
		return CasemapGolden{}, err
	}
	defer sb.remove()
	g := CasemapGolden{Header: header}
	if err := r.runDriver(ctx, sb, "record_casemap.py", struct{}{}, &g.CasemapBody); err != nil {
		return CasemapGolden{}, err
	}
	return g, nil
}

// GenerateCasemapTables は casemap.json から internal/pyunicode の大文字小文字の表の Go のソースを作る。
// 表は Python の str のメソッドを読んだ結果そのもので、手で編集しない。同じ記録からは同じバイト列ができる。
func GenerateCasemapTables(g CasemapGolden) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by ja-writing/oracle from testdata/golden/casemap.json (make golden); DO NOT EDIT.\n\npackage pyunicode\n\n")
	for _, t := range []struct {
		name, doc string
		rows      []CaseRow
	}{
		{"casefoldTable", "str.casefold が 1 字を変える結果 (cp の昇順)。", g.Casefold},
		{"lowerTable", "str.lower が 1 字を変える結果 (cp の昇順。語末の Σ の規則は含まない)。", g.Lower},
		{"swapcaseTable", "str.swapcase が 1 字を変える結果 (cp の昇順)。", g.Swapcase},
	} {
		if len(t.rows) == 0 {
			return nil, fmt.Errorf("記録に %s の行がありません", t.name)
		}
		fmt.Fprintf(&b, "// %s は %s\nvar %s = [...]decomposition{\n", t.name, t.doc, t.name)
		for _, row := range t.rows {
			fmt.Fprintf(&b, "\t{0x%x, %s},\n", row.CP, escapedRunes(row.To))
		}
		b.WriteString("}\n\n")
	}
	for _, t := range []struct {
		name, doc string
		rs        []CPRange
	}{
		{"casedRanges", "語末の Σ の規則で、大文字小文字のある字として数える字の範囲。", g.Cased},
		{"caseIgnorableRanges", "語末の Σ の規則で読み飛ばす字の範囲。", g.CaseIgnorable},
	} {
		if len(t.rs) == 0 {
			return nil, fmt.Errorf("記録に %s の範囲がありません", t.name)
		}
		fmt.Fprintf(&b, "// %s は %s\nvar %s = [...]runeRange{\n", t.name, t.doc, t.name)
		for _, r := range t.rs {
			fmt.Fprintf(&b, "\t{0x%x, 0x%x},\n", r.Lo, r.Hi)
		}
		b.WriteString("}\n\n")
	}
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("生成した Go のソースを整形できません: %w", err)
	}
	return append(bytes.TrimRight(out, "\n"), '\n'), nil
}
