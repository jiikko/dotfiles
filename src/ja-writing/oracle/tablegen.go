package oracle

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strings"
)

// PyunicodeTablesPath は GenerateUnicodeTables の出力の置き場 (module の根から)。
const PyunicodeTablesPath = "internal/pyunicode/tables_gen.go"

// GenerateUnicodeTables は unicode.json の記録から internal/pyunicode の表の Go のソースを作る。
// 表は Python の unicodedata を読んだ結果そのもので、手で編集しない。同じ記録からは同じバイト列ができる。
// 文字列は \u の形に直す (双方向制御文字などを生のままソースに置かない)。
func GenerateUnicodeTables(g UnicodeGolden) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by ja-writing/oracle from testdata/golden/unicode.json (make golden); DO NOT EDIT.\n\n")
	b.WriteString("package pyunicode\n\n")
	fmt.Fprintf(&b, "// UnicodeVersion は表のもとにした Python の unicodedata のバージョン。\nconst UnicodeVersion = %q\n\n", g.Header.UnicodedataVersion)

	names := categoryNames(g.Categories)
	b.WriteString("var categoryNames = [...]string{")
	for i, n := range names {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", n)
	}
	b.WriteString("}\n\n")
	b.WriteString("// categoryRuns は {開始, categoryNames の添字}。次の開始の手前までがその値で、最後は 0x10FFFF まで。\nvar categoryRuns = [...]categoryRun{\n")
	for _, c := range g.Categories {
		fmt.Fprintf(&b, "\t{0x%x, %d},\n", c.Start, slices.Index(names, c.Cat))
	}
	b.WriteString("}\n\n")

	for _, p := range []struct{ key, name string }{
		{"space", "spaceRanges"}, {"alpha", "alphaRanges"}, {"decimal", "decimalRanges"}, {"digit", "digitRanges"},
		{"numeric", "numericRanges"}, {"linebreak", "linebreakRanges"}, {"identifier_start", "identStartRanges"}, {"identifier_continue", "identContinueRanges"},
	} {
		rs, ok := g.Props[p.key]
		if !ok || len(rs) == 0 {
			return nil, fmt.Errorf("記録に %s の範囲がありません", p.key)
		}
		fmt.Fprintf(&b, "var %s = [...]runeRange{\n", p.name)
		for _, r := range rs {
			fmt.Fprintf(&b, "\t{0x%x, 0x%x},\n", r.Lo, r.Hi)
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("// combiningRuns は結合クラスが 0 でない範囲 {lo, hi, クラス}。\nvar combiningRuns = [...]combiningRun{\n")
	for _, r := range g.CCC {
		fmt.Fprintf(&b, "\t{0x%x, 0x%x, %d},\n", r.Lo, r.Hi, r.Class)
	}
	b.WriteString("}\n\n")

	for _, d := range []struct {
		name string
		rows []Decomp
	}{{"canonicalDecomp", g.NFD}, {"compatDecomp", g.NFKD}} {
		fmt.Fprintf(&b, "// %s は 1 字を最後まで分解した結果 (ハングルの音節は算法で決まるので入れない)。開始 cp の昇順。\nvar %s = [...]decomposition{\n", d.name, d.name)
		for _, row := range d.rows {
			fmt.Fprintf(&b, "\t{0x%x, %s},\n", row.CP, escapedRunes(row.To))
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("// composePairs は主合成 {先頭, 続き, 合成した字}。(先頭, 続き) の昇順。\nvar composePairs = [...]composePair{\n")
	for _, p := range g.Compose {
		fmt.Fprintf(&b, "\t{0x%x, 0x%x, 0x%x},\n", p.First, p.Second, p.Composite)
	}
	b.WriteString("}\n")

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("生成した Go のソースを整形できません: %w", err)
	}
	return append(bytes.TrimRight(out, "\n"), '\n'), nil
}

func categoryNames(runs []CategoryRun) []string {
	seen := map[string]bool{}
	var names []string
	for _, r := range runs {
		if !seen[r.Cat] {
			seen[r.Cat] = true
			names = append(names, r.Cat)
		}
	}
	slices.Sort(names)
	return names
}

func escapedRunes(rs []rune) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range rs {
		fmt.Fprintf(&b, `\U%08x`, r)
	}
	b.WriteByte('"')
	return b.String()
}
