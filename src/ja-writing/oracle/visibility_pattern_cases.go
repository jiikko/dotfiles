// alphabetPatterns は短い並びの全部 (走査の分岐と re.compile の誤りを、手書きで思いつけない形まで広げて本家と突き合わせる)。
func alphabetPatterns() []string {
	const wide = "a\\[]()?*+{}|^$.-1,:=!<P#>&"
	const narrow = "a\\[]()?{}1,"
	var out []string
	var gen func(prefix string, alphabet []rune, length int)
	gen = func(prefix string, alphabet []rune, length int) {
		if length == 0 {
			return
		}
		for _, c := range alphabet {
			p := prefix + string(c)
			out = append(out, p)
			gen(p, alphabet, length-1)
		}
	}
	gen("", []rune(wide), 3)
	// 4 字は狭い字の集まり (それでも走査の分岐の組み合わせを 1 回ずつ通る)。3 字以下は上で通っているので 4 字だけを足す。
	var four func(prefix string, n int)
	four = func(prefix string, n int) {
		if n == 0 {
			out = append(out, prefix)
			return
		}
		for _, c := range narrow {
			four(prefix+string(c), n-1)
		}
	}
	four("", 4)
	return out
}

func patternCases() []VisCase {
	var hand []Call
	for _, p := range handPatterns {
		hand = append(hand, vkeep(vcall("check_pattern", p)))
	}
	var generated []Call
	for _, p := range alphabetPatterns() {
		generated = append(generated, vcall("check_pattern", p))
	}
	return []VisCase{{Name: "check-pattern/hand", Calls: hand}, {Name: "check-pattern/alphabet", Calls: generated}}
}
