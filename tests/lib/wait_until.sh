# shellcheck shell=bash
# tests/lib/wait_until.sh — 「条件が成立するまで上限つきで待つ」の唯一の実装。
#
# 🚨 各テストへコピペしないこと。同じ形が 3 本へコピーされて名前とコメントの精度が乖離した
#   前例がある (tests/tmux/lib/stub_env.sh の注記 / issue 081)。実際、この関数を各ファイルに
#   書いた最初の版では「上限の書き方・出力先・log を dump するか」が 3 者で既に割れていた。
#
# なぜ固定 sleep を使わないか: `sleep N` が測っているのはその瞬間のマシンの空き具合で、
# **速いマシンでは緑のまま通り、負荷が上がった日にだけ落ちる** (並列実行を入れた瞬間に顕在化
# する)。正本は _claude/rules/avoid-wall-clock-assertions.md。
#
# 🚨 条件は**コマンド (関数名 + 引数)** で渡す。`tt_wait_until test -n "$(...)"` と書くと
#   コマンド置換が**呼び出し時に 1 度だけ**展開され、同じ値を上限まで見続ける = 必ず時間切れ
#   になる ("観測しているつもり" のループ)。
#
# 🚨 診断と終了は**呼び出し側**が持つ。ここで exit すると、待ちたいものごとに違う
#   「何を見れば分かるか」(ログ / ディレクトリの中身 / ps の該当行) を出せなくなる。
#   返すのは rc だけ: 成立=0 / 時間切れ=1。
#
# 上限は既定 10s (0.1s × 100)。**元の固定 sleep より十分長く取ること** — ポーリングは
# 「速くする」ためのもので「短気にする」ためのものではない (遅いマシンで flaky になる)。
tt_wait_until() {  # 残り=条件コマンド
  local _wu_i=0
  while [ "$_wu_i" -lt "${TT_WAIT_TICKS:-100}" ]; do
    "$@" && return 0
    sleep "${TT_WAIT_TICK:-0.1}"
    _wu_i=$((_wu_i + 1))
  done
  return 1
}
